function setMessage(text, type = '') {
  els.message.textContent = text;
  els.message.className = `message ${type}`.trim();
  els.message.classList.toggle('hidden', !text);
}

function showSyncResult({ type = 'success', title, body, paths = [] }) {
  if (!els.syncResultDialog || !els.syncResultTitle || !els.syncResultBody || !els.syncResultMeta) {
    return;
  }
  els.syncResultTitle.textContent = title;
  els.syncResultBody.textContent = body;
  els.syncResultMeta.textContent = '';
  paths.filter(Boolean).forEach((path) => {
    const code = document.createElement('code');
    code.textContent = path;
    els.syncResultMeta.appendChild(code);
  });
  if (els.syncResultCard) {
    els.syncResultCard.className = `syncResultCard ${type === 'error' ? 'error' : ''}`.trim();
  }
  els.syncResultDialog.classList.remove('hidden');
}

function closeSyncResult() {
  if (els.syncResultDialog) {
    els.syncResultDialog.classList.add('hidden');
  }
}

