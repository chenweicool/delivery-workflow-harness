function setLoading(button, loading, text) {
  button.disabled = loading;
  if (loading && text) {
    button.dataset.idleText = button.dataset.idleText || getIdleButtonText(button);
    button.textContent = text;
    return;
  }
  if (!loading) {
    button.textContent = getIdleButtonText(button);
  }
}

